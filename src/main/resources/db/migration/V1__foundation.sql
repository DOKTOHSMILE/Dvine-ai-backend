CREATE TABLE users (
    id VARCHAR(36) PRIMARY KEY,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE sessions (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL REFERENCES users (id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    device_id VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP
);

CREATE TABLE desk_rooms (
    id VARCHAR(36) PRIMARY KEY,
    owner_user_id VARCHAR(36) NOT NULL REFERENCES users (id),
    title VARCHAR(120),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE tasks (
    id VARCHAR(36) PRIMARY KEY,
    owner_user_id VARCHAR(36) NOT NULL REFERENCES users (id),
    desk_room_id VARCHAR(36) NOT NULL REFERENCES desk_rooms (id),
    request_id VARCHAR(80) NOT NULL,
    state VARCHAR(40) NOT NULL,
    input_text VARCHAR(4000) NOT NULL,
    result_text VARCHAR(8000),
    idempotency_key VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    UNIQUE (owner_user_id, idempotency_key)
);

CREATE TABLE task_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id VARCHAR(36) NOT NULL REFERENCES tasks (id),
    owner_user_id VARCHAR(36) NOT NULL,
    state VARCHAR(40) NOT NULL,
    agent VARCHAR(16),
    cue VARCHAR(16) NOT NULL,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX task_events_owner_idx ON task_events (task_id, owner_user_id, event_id);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(80) NOT NULL,
    owner_user_id VARCHAR(36),
    action VARCHAR(80) NOT NULL,
    decision VARCHAR(32) NOT NULL,
    object_ref VARCHAR(120),
    created_at TIMESTAMP NOT NULL
);
